// يبني كروت المية جوه شبكة معيّنة بلغة معيّنة
// opts: { href } — لو موجود، الكارت نفسه يبقى لينك يودّي للمكان ده
function renderWaterGrid(gridId, items, lang, opts) {
  const grid = document.getElementById(gridId);
  if (!grid) return;
  const options = opts || {};

  grid.innerHTML = items.map((item) => {
    const c = item[lang] || item.ar;
    const href = typeof options.href === 'function' ? options.href(item) : options.href;
    const badge = c.badge ? `<span class="water-card__badge">${c.badge}</span>` : '';
    const inner = `
        ${badge}
        <img class="water-img" src="${item.img}" alt="" loading="lazy" draggable="false">
        <div class="water-card__overlay"></div>
        <div class="water-card__content">
          <h3 class="water-card__title">${c.title}</h3>
          <p class="water-card__text">${c.desc}</p>
        </div>`;

    if (href) {
      return `<a class="water-card reveal" href="${href}" aria-label="${c.title}">${inner}</a>`;
    }
    return `<div class="water-card reveal" tabindex="0" role="button" aria-label="${c.title}">${inner}</div>`;
  }).join('');

  // نجهّز التأثير على الكروت الجديدة فورًا
  initWaterCards();
  // نحدّث حالة أسهم الكاروسيل بعد بناء الكروت
  initCarousels();
}

// يبني كروت الإعلانات (صورة + شارة + عنوان + وصف + زر)
// opts: { href } وجهة الزر (نص أو دالة), { cardHref } الضغط على الكارت كله,
//       { idPrefix, indexOffset } للـid, { banner } لإعلان مميّز بعرض كامل
function renderAdsGrid(gridId, items, lang, opts) {
  const grid = document.getElementById(gridId);
  if (!grid) return;
  const options = opts || {};
  const t = i18n[lang] || i18n.ar;
  const prefix = options.idPrefix || 'ad-';
  const offset = options.indexOffset || 0;
  const resolve = (val, item, i) => (typeof val === 'function' ? val(item, i) : val);
  const pointsList = (cls, pts) => (pts && pts.length)
    ? `<ul class="${cls}">${pts.map((p) => `<li>${p}</li>`).join('')}</ul>`
    : '';

  grid.innerHTML = items.map((item, i) => {
    const c = item[lang] || item.ar;
    const href = resolve(options.href, item, i) || item.link || 'contact.html';
    const cardHref = resolve(options.cardHref, item, i) || '';
    const id = prefix + (offset + i);
    const cardAttrs = cardHref ? ` data-card-href="${cardHref}" tabindex="0" role="link"` : '';

    if (options.banner) {
      const badge = c.badge ? `<span class="ad-feature__badge">${c.badge}</span>` : '';
      return `
        <article class="ad-feature reveal" id="${id}"${cardAttrs}>
          <img class="ad-feature__img" src="${item.img}" alt="" loading="lazy" draggable="false">
          <div class="ad-feature__overlay"></div>
          <div class="ad-feature__content">
            ${badge}
            <h3 class="ad-feature__title">${c.title}</h3>
            <p class="ad-feature__text">${c.desc}</p>
            ${pointsList('ad-feature__points', c.points)}
            <a class="ad-feature__btn" href="${href}">${c.btn || t.adBtn || 'اعرف أكثر'}</a>
          </div>
        </article>`;
    }

    const badge = c.badge ? `<span class="ad-card__badge">${c.badge}</span>` : '';
    const rowClass = options.layout === 'row' ? ' ad-card--row' : '';
    return `
      <article class="ad-card reveal${rowClass}" id="${id}"${cardAttrs}>
        <div class="ad-card__media">
          <img src="${item.img}" alt="" loading="lazy" draggable="false">
          ${badge}
        </div>
        <div class="ad-card__body">
          <h3 class="ad-card__title">${c.title}</h3>
          <p class="ad-card__text">${c.desc}</p>
          ${pointsList('ad-card__points', c.points)}
          <a class="ad-card__btn" href="${href}">${c.btn || t.adBtn || 'اعرف أكثر'}</a>
        </div>
      </article>`;
  }).join('');

  // لو الصفحة اتفتحت بلينك فيه #ad-x نبرز الإعلان المختار
  highlightFromHash();
}

// إبراز الإعلان اللي اتفتح بيه الرابط (offers.html#ad-2 مثلاً) + التمرير له
function highlightFromHash() {
  const hash = window.location.hash || '';
  if (hash.indexOf('#ad-') !== 0) return;
  const el = document.getElementById(hash.slice(1));
  if (!el) return;
  el.classList.add('is-highlight');
  setTimeout(() => {
    try { el.scrollIntoView({ behavior: 'smooth', block: 'center' }); } catch (e) { el.scrollIntoView(); }
  }, 150);
}

// الضغط على أي كارت مكتوب عليه data-card-href يفتح وجهته (كارت الإعلان كله)
function initCardLinks() {
  const go = (e) => {
    const card = e.target.closest('[data-card-href]');
    if (!card) return;
    if (e.target.closest('a')) return; // الأزرار والروابط الحقيقية تتعامل بنفسها
    const href = card.getAttribute('data-card-href');
    if (href) window.location.href = href;
  };
  document.addEventListener('click', go);
  document.addEventListener('keydown', (e) => {
    if (e.key !== 'Enter' && e.key !== ' ') return;
    go(e);
  });
}


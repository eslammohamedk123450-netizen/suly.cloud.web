// ---------- كاروسيل الصف الأفقي (خدماتنا / مشاريعنا) ----------
function carouselStep(track) {
  const card = track.querySelector('.water-card');
  if (!card) return track.clientWidth * 0.8;
  const styles = getComputedStyle(track);
  const gap = parseFloat(styles.columnGap) || parseFloat(styles.gap) || 24;
  return card.getBoundingClientRect().width + gap;
}

function updateCarousel(root) {
  const track = root.querySelector('.carousel__track');
  const prev = root.querySelector('.carousel__btn--prev');
  const next = root.querySelector('.carousel__btn--next');
  if (!track || !prev || !next) return;
  const max = track.scrollWidth - track.clientWidth;
  const pos = Math.abs(track.scrollLeft);
  prev.disabled = pos <= 2;
  next.disabled = max <= 2 || pos >= max - 2;
}

function updateCarousels() {
  document.querySelectorAll('[data-carousel]').forEach(updateCarousel);
}

function setupCarousel(root) {
  if (root.dataset.carouselReady) { updateCarousel(root); return; }
  root.dataset.carouselReady = '1';

  const track = root.querySelector('.carousel__track');
  const prev = root.querySelector('.carousel__btn--prev');
  const next = root.querySelector('.carousel__btn--next');
  if (!track || !prev || !next) return;

  const isRTL = () => getComputedStyle(track).direction === 'rtl';
  const go = (dir) => {
    // في RTL اتجاه التمرير بيتقلب
    const amount = carouselStep(track) * dir * (isRTL() ? -1 : 1);
    track.scrollBy({ left: amount, behavior: 'smooth' });
  };

  prev.addEventListener('click', () => go(-1));
  next.addEventListener('click', () => go(1));
  track.addEventListener('scroll', () => updateCarousel(root), { passive: true });
  window.addEventListener('resize', () => updateCarousel(root));

  // عجلة الماوس تمرّر الصف أفقيًا (بس لو الصف نفسه لسه محتاج تمرير)
  track.addEventListener('wheel', (e) => {
    const max = track.scrollWidth - track.clientWidth;
    if (max <= 2 || Math.abs(e.deltaX) > Math.abs(e.deltaY)) return;
    const pos = Math.abs(track.scrollLeft);
    const toEnd = e.deltaY > 0;
    if ((toEnd && pos < max - 2) || (!toEnd && pos > 2)) {
      track.scrollBy({ left: (isRTL() ? -1 : 1) * e.deltaY });
      e.preventDefault();
    }
  }, { passive: false });

  updateCarousel(root);
}

function initCarousels() {
  document.querySelectorAll('[data-carousel]').forEach(setupCarousel);
}


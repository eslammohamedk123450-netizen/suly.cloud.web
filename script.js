// ---------- أنيميشن النص (text-pop-up-top) ----------
function makeSpace() {
  const s = document.createElement('span');
  s.className = 'space';
  s.textContent = '\u00A0';
  return s;
}

function makeLetter(text, index) {
  const s = document.createElement('span');
  s.className = 'letter';
  s.textContent = text;
  s.style.whiteSpace = 'nowrap';
  // تأخير كل حرف/كلمة عشان تطلع ورا بعض
  s.style.animationDelay = (0.1 * (index + 1)).toFixed(2) + 's';
  return s;
}

// عنوان الهيرو: كلمة-كلمة (عشان العربي يفضل متصل والإنجليزي ما يتقطعش في نص الكلمة)
function buildHeroTitle(text) {
  const el = document.querySelector('.hero__title');
  if (!el) return;

  const value = (text != null ? text : el.textContent).trim();
  const isArabic = /[\u0600-\u06FF]/.test(value);

  el.style.direction = isArabic ? 'rtl' : 'ltr';
  el.style.letterSpacing = isArabic ? 'normal' : '-2px';
  el.textContent = '';

  let index = 0;
  value.split(/\s+/).forEach((word, w) => {
    if (w > 0) { el.appendChild(makeSpace()); index++; }
    el.appendChild(makeLetter(word, index));
    index++;
  });
}

// اسم الشركة: حرف-حرف
function buildBrandName(text) {
  const el = document.getElementById('brandName');
  if (!el) return;

  const value = (text != null ? text : el.textContent).trim();
  el.textContent = '';

  [...value].forEach((ch, i) => {
    if (ch === ' ') { el.appendChild(makeSpace()); return; }
    el.appendChild(makeLetter(ch, i));
  });
}

// ---------- تأثير المية على الكروت (Water Cards) ----------
// يشتغل على أي عنصر عليه كلاس water-card: كانفس موجات + رِبل عند الدوس + بارالاكس للصورة.
function initWaterCards() {
  document.querySelectorAll('.water-card:not([data-water-ready])').forEach((card) => {
    card.dataset.waterReady = '1';

    // كانفس الموجات — فوق كل حاجة بس مش بيمنع الضغط
    const canvas = document.createElement('canvas');
    canvas.className = 'water-canvas';
    card.appendChild(canvas);
    const ctx = canvas.getContext('2d');

    // الصورة اللي جوه الكارت — بنحركها سنة مع الماوس
    const img = card.querySelector('img');
    if (img) img.classList.add('water-img');

    let ripples = [];
    let drops = [];
    let running = false;

    function resize() {
      const r = card.getBoundingClientRect();
      canvas.width = r.width * 2;
      canvas.height = r.height * 2;
    }
    resize();
    new ResizeObserver(resize).observe(card);

    let lastMove = 0;
    function getPos(e) {
      const r = card.getBoundingClientRect();
      const cx = e.clientX != null ? e.clientX : (e.touches && e.touches[0] ? e.touches[0].clientX : 0);
      const cy = e.clientY != null ? e.clientY : (e.touches && e.touches[0] ? e.touches[0].clientY : 0);
      return { x: cx - r.left, y: cy - r.top, w: r.width, h: r.height };
    }

    // حركة الماوس / صباعك = موجات صغيرة
    function onMove(e) {
      const { x, y, w, h } = getPos(e);
      const now = Date.now();
      if (now - lastMove > 90) {
        lastMove = now;
        drops.push({ x: x * 2, y: y * 2, r: 2, max: 60 + Math.random() * 30, alpha: 0.45 });
        ensureDraw();
      }
      if (img) {
        const cx = (x / w - 0.5) * 8;
        const cy = (y / h - 0.5) * 8;
        img.style.transform = `scale(1.08) translate(${cx}px, ${cy}px)`;
      }
    }

    // الدوسة = حجر في مية
    function onDown(e) {
      const { x, y } = getPos(e);
      [0, 120, 240].forEach((delay) => {
        setTimeout(() => {
          if (!card.isConnected) return;
          const ring = document.createElement('div');
          ring.className = 'ripple-ring';
          ring.style.left = x + 'px';
          ring.style.top = y + 'px';
          ring.style.width = '10px';
          ring.style.height = '10px';
          card.appendChild(ring);
          const anim = ring.animate([
            { transform: 'translate(-50%,-50%) scale(0)', opacity: 0.9, width: '10px', height: '10px' },
            { transform: 'translate(-50%,-50%) scale(1)', opacity: 0, width: '320px', height: '320px' }
          ], { duration: 900, easing: 'cubic-bezier(.1,.6,.2,1)' });
          anim.onfinish = () => ring.remove();
          ripples.push({ x: x * 2, y: y * 2, r: 5, max: 320, alpha: 0.9, width: 3 });
          ensureDraw();
        }, delay);
      });
      card.animate([
        { transform: 'scale(1)' },
        { transform: 'scale(.985)' },
        { transform: 'scale(1)' }
      ], { duration: 450, easing: 'ease-out' });
    }

    card.addEventListener('mousemove', onMove);
    card.addEventListener('touchmove', onMove, { passive: true });
    card.addEventListener('pointerdown', onDown);

    // رسم الموجات — بيشتغل بس لما يكون فيه نشاط، وبيوقف لما الكارت يتشال من الصفحة
    function draw() {
      if (!card.isConnected) { running = false; return; }

      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ripples = ripples.filter((r) => r.r < r.max);
      ripples.forEach((r) => {
        r.r += 6; r.alpha *= 0.96;
        ctx.beginPath(); ctx.arc(r.x, r.y, r.r, 0, Math.PI * 2);
        ctx.strokeStyle = `rgba(255,255,255,${r.alpha})`; ctx.lineWidth = r.width; ctx.stroke();
        ctx.beginPath(); ctx.arc(r.x, r.y, r.r * 0.6, 0, Math.PI * 2);
        ctx.strokeStyle = `rgba(255,255,255,${r.alpha * 0.5})`; ctx.lineWidth = 1.5; ctx.stroke();
      });
      drops = drops.filter((d) => d.r < d.max);
      drops.forEach((d) => {
        d.r += 2.2; d.alpha *= 0.97;
        ctx.beginPath(); ctx.arc(d.x, d.y, d.r, 0, Math.PI * 2);
        ctx.strokeStyle = `rgba(255,255,255,${d.alpha})`; ctx.lineWidth = 1.5; ctx.stroke();
      });

      if (ripples.length || drops.length) {
        requestAnimationFrame(draw);
      } else {
        running = false;
      }
    }

    function ensureDraw() {
      if (running) return;
      running = true;
      requestAnimationFrame(draw);
    }
  });
}

initWaterCards();
new MutationObserver(initWaterCards).observe(document.body, { childList: true, subtree: true });

